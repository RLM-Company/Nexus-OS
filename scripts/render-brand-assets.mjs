import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { format, resolveConfig } from "prettier";

// Preserve the owner's selected white helmet, black visor and black orbit.
// The canonical source is raster artwork; SVG outputs are image wrappers.
const source = await readFile("assets/brand/kosmora-symbol.png");
const webRequire = createRequire(resolve("apps/web/package.json"));
const nextRequire = createRequire(webRequire.resolve("next/package.json"));
const sharp = nextRequire("sharp");
const metadata = await sharp(source).metadata();
if (!metadata.hasAlpha) throw new Error("The Kosmora source must preserve transparency");
const symbol = await sharp(source)
  .trim({ background: "#00000000" })
  .resize(256, 256, { fit: "contain", background: "#00000000" })
  .png()
  .toBuffer();
const symbolData = `data:image/png;base64,${symbol.toString("base64")}`;
const color = "#6552b8";
const glyph = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="32" height="32" aria-hidden="true"><image href="${symbolData}" width="64" height="64"/></svg>`;
// The 288px foreground square fits in the central maskable safe circle:
// sqrt(144^2 + 144^2) < 512 * 0.4. No ring or helmet is clipped by masking.
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Kosmora"><rect width="512" height="512" fill="${color}"/><image href="${symbolData}" x="112" y="112" width="288" height="288"/></svg>\n`;
const generated = `// Generated by scripts/render-brand-assets.mjs from assets/brand/kosmora-symbol.png.\nexport const KOSMORA_SYMBOL_DATA_URL =\n  ${JSON.stringify(symbolData)};\n`;
const generatedIcon = `// Generated by scripts/render-brand-assets.mjs from assets/brand/kosmora-symbol.png.\nexport const KOSMORA_APP_ICON_SVG =\n  ${JSON.stringify(icon.trim())};\n`;
const ownerFile = "deploy/alpha/owner-access.mjs";
const owner = await readFile(ownerFile, "utf8");
const marker = /\/\/ BEGIN GENERATED COSMORA BRAND[\s\S]*?\/\/ END GENERATED COSMORA BRAND/u;
if (!marker.test(owner)) throw new Error("Owner login brand generation marker is missing");
const ownerUpdated = owner.replace(
  marker,
  `// BEGIN GENERATED COSMORA BRAND\nconst brandSymbol =\n  ${JSON.stringify(glyph)};\n// END GENERATED COSMORA BRAND`
);
const sizes = [16, 24, 32, 48, 64, 128, 256];
const buffers = await Promise.all(
  sizes.map((size) => sharp(Buffer.from(icon)).resize(size, size).png().toBuffer())
);
const header = Buffer.alloc(6 + sizes.length * 16);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
buffers.forEach((buffer, index) => {
  const position = 6 + index * 16;
  header[position] = sizes[index] === 256 ? 0 : sizes[index];
  header[position + 1] = header[position];
  header.writeUInt16LE(1, position + 4);
  header.writeUInt16LE(32, position + 6);
  header.writeUInt32LE(buffer.length, position + 8);
  header.writeUInt32LE(offset, position + 12);
  offset += buffer.length;
});
const outputs = [
  ["apps/web/src/app/kosmora-brand.generated.ts", Buffer.from(generated)],
  ["apps/web/src/app/kosmora-icon.generated.ts", Buffer.from(generatedIcon)],
  ["apps/web/public/brand/kosmora-symbol.png", symbol],
  ["assets/brand/kosmora-app-icon.svg", Buffer.from(icon)],
  ["desktop/windows/build/icon.svg", Buffer.from(icon)],
  ["desktop/windows/build/icon.ico", Buffer.concat([header, ...buffers])],
  [ownerFile, Buffer.from(ownerUpdated)]
];
for (const [file, rawContent] of outputs) {
  const content =
    file.endsWith(".ico") || file.endsWith(".svg") || file.endsWith(".png")
      ? rawContent
      : Buffer.from(
          await format(rawContent.toString("utf8"), {
            ...(await resolveConfig(file)),
            filepath: file
          })
        );
  if (process.argv.includes("--check")) {
    if (!(await readFile(file)).equals(content)) throw new Error(`Stale brand asset: ${file}`);
  } else {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}
console.log(`Kosmora brand assets ${process.argv.includes("--check") ? "verified" : "rendered"}`);
